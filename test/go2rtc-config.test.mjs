/** Modified for genomez S1 experimental source preview, 2026-10-14. */
// The generated go2rtc config is what every consumer ends up pulling, so its source line carries the
// flags that decide whether a stream is usable. `#async` re-stamps frames from the wall clock: without
// it the eufy feed's own timestamps (dts 0, then a jump) make Home Assistant abort a picture that is
// already flowing — "Timestamp discontinuity detected: last dts = 0, dts = 4219155056".
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import assert from "node:assert/strict";

import { writeGo2rtcConfig } from "../go2rtc-config.mjs";

const cams = [
  { sn: "CAM1", stream: "/stream/CAM1" },
  { sn: "SENSOR1" }, // no stream path → not a camera, must not appear
];

async function generate(devices = cams) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "go2rtc-"));
  const file = path.join(dir, "go2rtc.yaml");
  const before = JSON.stringify(devices);
  try {
    const sns = await writeGo2rtcConfig({ go2rtcConfig: file, selfHost: "127.0.0.1", port: 3000 }, devices);
    assert.equal(JSON.stringify(devices), before, "device metadata must remain unchanged");
    return { yaml: fs.readFileSync(file, "utf8"), sns };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

test("every camera stream is generated with #async", async () => {
  const { yaml, sns } = await generate();
  assert.deepEqual(sns, ["CAM1"]);
  assert.match(yaml, /CAM1: ffmpeg:http:\/\/127\.0\.0\.1:3000\/stream\/CAM1#video=copy#async/);
});

test("a device without a stream path is left out", async () => {
  const { yaml } = await generate();
  assert.ok(!yaml.includes("SENSOR1"), "non-camera devices must not become go2rtc streams");
});

// Synthetic cases retained from the startup generator qualification.
const header =
  '# generated by ha-eufy-sdk-bridge at startup \u2014 do not edit (contains real serials)\napi:\n  listen: ":1984"\nrtsp:\n  listen: ":8554"\nwebrtc:\n  listen: ":8555"\n';
const template = 'ffmpeg:\n  s1-startup: "-flags low_delay -fpsprobesize 0 -i {input}"\n';
const route = (sn, video, named = false) =>
  `  ${sn}: ffmpeg:http://127.0.0.1:3000/stream/${sn}#video=${video}#async${named ? "#input=s1-startup" : ""}\n`;
const camera = (extra = {}) => ({
  sn: "SYNTH_CAMERA",
  stationSn: "SYNTH_RTC",
  stream: "/stream/SYNTH_CAMERA",
  ...extra,
});
const parent = (extra = {}) => ({ sn: "SYNTH_RTC", model: "T9000", ...extra });

for (const model of ["T9000", "t9000", "T9000 S1 Pro"]) {
  test(`startup input requires a unique positive parent: ${model}`, async () => {
    const { yaml, sns } = await generate([parent({ model }), camera()]);
    assert.equal(yaml, header + template + "streams:\n" + route("SYNTH_CAMERA", "h264", true));
    assert.deepEqual(sns, ["SYNTH_CAMERA"]);
  });
}

const ordinaryCases = [
  ["non-S1 parent", [parent({ model: "T8010" }), camera()]],
  ["missing parent", [camera()]],
  ["null parent reference", [parent(), camera({ stationSn: null })]],
  ["undefined parent reference", [parent(), camera({ stationSn: undefined })]],
  ["camera model alone", [camera({ stationSn: null, model: "T9000" })]],
  ["unknown parent model", [parent({ model: undefined }), camera()]],
  ["empty roster", []],
  ["station without camera", [parent()]],
  ["numeric parent model", [parent({ model: 9000 }), camera()]],
  ["substring parent model", [parent({ model: "HomeBase T9000" }), camera()]],
];
for (const [name, devices] of ordinaryCases) {
  test(`copy producer remains exact without a positive parent: ${name}`, async () => {
    const { yaml, sns } = await generate(devices);
    assert.equal(
      yaml,
      header +
        "streams:\n" +
        devices
          .filter((d) => d.stream)
          .map((d) => route(d.sn, "copy"))
          .join(""),
    );
    assert.deepEqual(
      sns,
      devices.filter((d) => d.stream).map((d) => d.sn),
    );
  });
}

// Expected legacy video selection is explicit; malformed identity must never enable the template.
const malformedCases = [
  ["undefined serial coincidence", [{ model: "T9000" }, camera({ stationSn: undefined })], "h264"],
  ["null serial coincidence", [parent({ sn: null }), camera({ stationSn: null })], "h264"],
  ["empty serial coincidence", [parent({ sn: "" }), camera({ stationSn: "" })], "h264"],
  ["numeric parent identity", [parent({ sn: 123 }), camera({ stationSn: 123 })], "h264"],
  [
    "object parent identity",
    (() => {
      const ref = {};
      return [parent({ sn: ref }), camera({ stationSn: ref })];
    })(),
    "h264",
  ],
  ["whitespace parent identity", [parent({ sn: " SYNTH_RTC" }), camera({ stationSn: " SYNTH_RTC" })], "h264"],
  ["numeric camera identity", [parent(), camera({ sn: 123 })], "h264"],
  ["empty camera identity", [parent(), camera({ sn: "" })], "h264"],
  ["whitespace camera identity", [parent(), camera({ sn: " SYNTH_CAMERA" })], "h264"],
  ["self parent", [camera({ stationSn: "SYNTH_CAMERA", model: "T9000" })], "h264"],
  ["duplicate T9000 parent", [parent(), parent(), camera()], "h264"],
  ["conflicting duplicate parent", [parent(), parent({ model: "T8010" }), camera()], "h264"],
  ["conflicting duplicate reversed", [parent({ model: "T8010" }), parent(), camera()], "copy"],
  ["array model coercion", [parent({ model: ["T9000"] }), camera()], "h264"],
  ["object model coercion", [parent({ model: { toString: () => "T9000" } }), camera()], "h264"],
  ["wrong type exact serial", [parent({ sn: 123 }), camera({ stationSn: "123" })], "copy"],
];
for (const [name, devices, video] of malformedCases) {
  test(`malformed binding preserves the legacy route without startup override: ${name}`, async () => {
    const { yaml, sns } = await generate(devices);
    assert.equal(
      yaml,
      header +
        "streams:\n" +
        devices
          .filter((d) => d.stream)
          .map((d) => route(d.sn, video))
          .join(""),
    );
    assert.deepEqual(
      sns,
      devices.filter((d) => d.stream).map((d) => d.sn),
    );
  });
}

test("mixed roster emits the startup template once and preserves producer order", async () => {
  const devices = [
    camera({ sn: "SYNTH_OTHER", stationSn: "SYNTH_OTHER_BASE" }),
    parent(),
    parent({ sn: "SYNTH_OTHER_BASE", model: "T8010" }),
    camera(),
    camera({ sn: "SYNTH_ORPHAN", stationSn: "SYNTH_MISSING" }),
    camera({ sn: "SYNTH_SECOND" }),
    parent({ sn: "SYNTH_AMBIGUOUS" }),
    parent({ sn: "SYNTH_AMBIGUOUS" }),
    camera({ sn: "SYNTH_LEGACY", stationSn: "SYNTH_AMBIGUOUS" }),
  ];
  const { yaml, sns } = await generate(devices);
  assert.equal(
    yaml,
    header +
      template +
      "streams:\n" +
      route("SYNTH_OTHER", "copy") +
      route("SYNTH_CAMERA", "h264", true) +
      route("SYNTH_ORPHAN", "copy") +
      route("SYNTH_SECOND", "h264", true) +
      route("SYNTH_LEGACY", "h264"),
  );
  assert.deepEqual(sns, ["SYNTH_OTHER", "SYNTH_CAMERA", "SYNTH_ORPHAN", "SYNTH_SECOND", "SYNTH_LEGACY"]);
  assert.equal(yaml.match(/  s1-startup:/g).length, 1);
});

test("startup template has only the retained options and no global input override", async () => {
  const { yaml } = await generate([parent(), camera()]);
  const value = yaml.match(/^  s1-startup: "([^"]+)"$/m)[1];
  assert.deepEqual(value.split(" "), ["-flags", "low_delay", "-fpsprobesize", "0", "-i", "{input}"]);
  assert.equal(value.match(/-i /g).length, 1);
  assert.ok(!yaml.includes("  http:"));
  for (const forbidden of [
    "-fflags",
    "-analyzeduration",
    "-probesize",
    "-f h264",
    "-f hevc",
    "-c:v",
    "-pix_fmt",
    "timeout",
    "stats",
    "FFREPORT",
  ])
    assert.ok(!yaml.includes(forbidden));
});
